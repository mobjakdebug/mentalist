-- 0. جدول کاربران و احراز هویت (Users & Authentication)
CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE,
    password_hash TEXT NOT NULL,
    avatar_emoji TEXT NOT NULL DEFAULT '🕵️',
    level INTEGER NOT NULL DEFAULT 1,
    xp INTEGER NOT NULL DEFAULT 0,
    coins INTEGER NOT NULL DEFAULT 0,
    matches_played INTEGER NOT NULL DEFAULT 0,
    wins INTEGER NOT NULL DEFAULT 0,
    successful_bluffs INTEGER NOT NULL DEFAULT 0,
    correct_guesses INTEGER NOT NULL DEFAULT 0,
    ghost_badges INTEGER NOT NULL DEFAULT 0,
    truthseeker_badges INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL,
    last_login INTEGER NOT NULL
);

-- 0.1 جدول سشن‌ها و توکن‌های امنیتی لاگین (Auth Sessions)
CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    expires_at INTEGER NOT NULL,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 1. جدول اتاق‌های بازی (Rooms)
CREATE TABLE IF NOT EXISTS rooms (
    id TEXT PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    host_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'LOBBY', -- LOBBY, ANSWERING, SHUFFLING, INTERROGATION, GUESSING, REVEAL, SUMMARY, FINISHED
    current_round INTEGER NOT NULL DEFAULT 1,
    total_rounds INTEGER NOT NULL DEFAULT 4,
    current_mentalist_id TEXT,
    current_question_id INTEGER,
    used_question_ids TEXT NOT NULL DEFAULT '', -- شناسه سوالات مصرف شده در این مسابقه برای جلوگیری از تکرار
    phase_start_time INTEGER,
    phase_duration_seconds INTEGER DEFAULT 45,
    created_at INTEGER NOT NULL
);

-- 2. جدول بازیکنان متصل به هر اتاق (Players)
CREATE TABLE IF NOT EXISTS players (
    id TEXT PRIMARY KEY,
    room_code TEXT NOT NULL,
    user_id TEXT, -- پیوند به اکانت کاربری واقعی
    name TEXT NOT NULL,
    avatar_emoji TEXT NOT NULL DEFAULT '🕵️',
    level INTEGER NOT NULL DEFAULT 1,
    score INTEGER NOT NULL DEFAULT 0,
    round_score_delta INTEGER NOT NULL DEFAULT 0,
    is_host INTEGER NOT NULL DEFAULT 0,
    is_mentalist INTEGER NOT NULL DEFAULT 0,
    has_answered INTEGER NOT NULL DEFAULT 0,
    last_ping INTEGER NOT NULL,
    joined_at INTEGER NOT NULL,
    FOREIGN KEY(room_code) REFERENCES rooms(code) ON DELETE CASCADE,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 3. جدول پرسش‌های روانشناسی و مچ‌گیری (Questions)
CREATE TABLE IF NOT EXISTS questions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    category TEXT NOT NULL,
    question_text TEXT NOT NULL,
    created_by TEXT DEFAULT 'SYSTEM'
);

-- 4. جدول پاسخ‌های محرمانه کارت‌ها (Answers)
CREATE TABLE IF NOT EXISTS answers (
    id TEXT PRIMARY KEY,
    room_code TEXT NOT NULL,
    round_number INTEGER NOT NULL,
    author_player_id TEXT NOT NULL,
    card_label TEXT NOT NULL, -- کارت الف، کارت ب، کارت ج، ...
    answer_text TEXT NOT NULL,
    assigned_player_id TEXT, -- مظنونی که بازجو به این کارت نسبت داده
    is_revealed INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL,
    FOREIGN KEY(room_code) REFERENCES rooms(code) ON DELETE CASCADE
);

-- 5. جدول پیام‌های چت اتاق بازجویی (Chat Messages)
CREATE TABLE IF NOT EXISTS messages (
    id TEXT PRIMARY KEY,
    room_code TEXT NOT NULL,
    player_id TEXT NOT NULL,
    player_name TEXT NOT NULL,
    text TEXT NOT NULL,
    is_mentalist INTEGER NOT NULL DEFAULT 0,
    is_system INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL,
    FOREIGN KEY(room_code) REFERENCES rooms(code) ON DELETE CASCADE
);

-- 6. جدول گزارش‌های تخلف و ترول (Reports)
CREATE TABLE IF NOT EXISTS reports (
    id TEXT PRIMARY KEY,
    room_code TEXT,
    reporter_name TEXT NOT NULL,
    target_name TEXT NOT NULL,
    message_text TEXT NOT NULL,
    reason TEXT NOT NULL,
    created_at INTEGER NOT NULL
);

-- ایندکس‌های بهینه‌سازی کوئری‌ها در Cloudflare D1
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_sessions_token ON sessions(token);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_players_room ON players(room_code);
CREATE INDEX IF NOT EXISTS idx_players_user ON players(user_id);
CREATE INDEX IF NOT EXISTS idx_answers_room_round ON answers(room_code, round_number);
CREATE UNIQUE INDEX IF NOT EXISTS idx_answers_unique_submission ON answers(room_code, round_number, author_player_id);
CREATE INDEX IF NOT EXISTS idx_messages_room ON messages(room_code, created_at);
CREATE INDEX IF NOT EXISTS idx_rooms_code ON rooms(code);

